#!/usr/bin/env node
// Writes docs/bmw-e90/READINESS-MATRIX.md from the generated drafts and the evidence ledgers (no judgement calls: counts only).
//   node scripts/bmw/readiness.mjs [--receipt path/to/receipt.json]
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const esbuild = createRequire(path.join(ROOT, "package.json"))("esbuild");
const out = await esbuild.build({ entryPoints: [path.join(ROOT, "src/data/admin-test-guides/bmw-2010-328i-drafts.ts")], bundle: true, write: false, format: "esm", platform: "node", logLevel: "silent", alias: { "@": path.join(ROOT, "src") } });
const { bmwDraftGuides } = await import("data:text/javascript;base64," + Buffer.from(out.outputFiles[0].text).toString("base64"));
const EVID = path.join(ROOT, "docs/bmw-e90/evidence");
const led = Object.fromEntries(fs.readdirSync(EVID).filter((f) => /^guide-\d\d\.json$/.test(f)).map((f) => { const g = JSON.parse(fs.readFileSync(path.join(EVID, f), "utf8")); return [g.guide, g]; }));
const a = process.argv.slice(2);
const rp = a.includes("--receipt") ? a[a.indexOf("--receipt") + 1] : null;
const receipt = rp ? JSON.parse(fs.readFileSync(rp, "utf8")) : null;
const BLOCK = "⛔ BLOCKED — ";
const rows = bmwDraftGuides.map(({ slug, guide }, i) => {
  const no = i + 1;
  const printed = guide.torqueSpecs.filter((t) => /\d/.test(t.value) && !/VERIFY EXACT/.test(t.value)).length;
  const verify = guide.torqueSpecs.length - printed;
  const blocked = guide.steps.filter((s) => s.title.startsWith(BLOCK)).map((s) => s.title.replace(BLOCK, ""));
  const inap = /Not applicable to this car/.test(guide.summary);
  const runs = receipt?.results.filter((r) => r.slug === slug) ?? [];
  const walked = receipt ? (runs.length >= 2 && runs.every((r) => r.pass) ? `pass (${runs.map((r) => r.viewport).join(", ")})` : "FAIL") : "n/a";
  const status = blocked.length ? "WORKING, with blocked steps" : "WORKING";
  return `| ${no} | ${guide.title.replace(/ — 2010 BMW 328i \(DRAFT\)/, "")} | ${status} | ${guide.steps.length} | ${walked} | ${printed} / ${verify} | ${blocked.length ? blocked.join("; ") : "none"} | ${inap ? "transfer case / front differential (xDrive only)" : "none"} | ${(led[no].missingEvidence ?? []).length} |`;
});
const md = `# BMW 328i (E90) readiness matrix (generated by scripts/bmw/readiness.mjs)

Vehicle: 2010 BMW 328i sedan, VIN WBAPH7C58AA175760 (probable RWD automatic N52). All 16 guides are admin-only uncertified drafts.
"Working" means: loads for this vehicle, Planning Mode shows tools/parts/safety/torque/steps, Wrench Mode walks every step forward and back with the right progress, no horizontal overflow or clipped text, no console errors, at desktop (1280), phone (390) and small-phone (320) widths. It does NOT mean certified: torque values flagged VERIFY stay flagged.

| # | Guide | Status | Steps | Browser walk (viewports) | Torque rows printed / flagged VERIFY | Blocked steps | Inapplicable | Open evidence items |
|---|---|---|---|---|---|---|---|---|
${rows.join("\n")}
${receipt ? `\nBrowser receipt: ${receipt.summary.passed}/${receipt.summary.total} runs passed (${receipt.summary.guideViewportRuns} guide x viewport, ${receipt.summary.errorStateRuns} error-state), ${receipt.at}.\n` : ""}`;
fs.writeFileSync(path.join(ROOT, "docs/bmw-e90/READINESS-MATRIX.md"), md);
console.log("wrote READINESS-MATRIX.md");
